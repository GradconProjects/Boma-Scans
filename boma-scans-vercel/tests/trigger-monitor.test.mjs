test("Armed plans track target hits in order and stop first, with the exit percentages", () => {
  const { armPlan, checkExits, parseArmedPlans } = mod.exports;
  const row = { symbol: "ABCUSDT", bias: "LONG", stop: 95, entryReady: true, executionPlan: { side: "LONG", trigger: 100, stop: 95, entry: 100.2, confirmationTime: 7 }, takeProfits: [101, 102, 103, 104, 105].map((price, i) => ({ price, exitPct: [30, 25, 20, 15, 10][i] })) };
  const plan = armPlan(row, 1000);
  assert.equal(plan.entry, 100.2); assert.equal(plan.hit, 0); assert.deepEqual(plan.weights, [30, 25, 20, 15, 10]);
  const t = 2000;
  let step = checkExits(plan, 100.5, t); assert.deepEqual(step.events, []); assert.equal(step.next.hit, 0);
  step = checkExits(step.next, 102.3, t);
  assert.deepEqual(step.events.map(e => [e.kind, e.level, e.exitPct]), [["TARGET", 1, 30], ["TARGET", 2, 25]]);
  assert.equal(step.next.hit, 2);
  step = checkExits(step.next, 101.5, t); assert.deepEqual(step.events, [], "no repeat after a pullback");
  step = checkExits(step.next, 94.9, t); assert.equal(step.events[0].kind, "STOP"); assert.equal(step.next, null);
  const done = checkExits({ ...plan, hit: 4 }, 105.1, t); assert.equal(done.events[0].level, 5); assert.equal(done.next, null, "all targets done");
  const short = checkExits({ ...plan, side: "SHORT", stop: 105, targets: [99, 98, 97, 96, 95] }, 97.5, t);
  assert.deepEqual(short.events.map(e => e.level), [1, 2]);
  assert.equal(parseArmedPlans([plan, { bad: true }]).length, 1);
});
test("Transition memory reports each step once: alert, confirmation, arm, targets, stop", () => {
  const { transitionMonitor } = mod.exports;
  const mkRow = (ready, status) => ({ symbol: "ABCUSDT", bias: "LONG", stop: 95, entryReady: ready, executionPlan: { side: "LONG", status, trigger: 100, entry: 100.2, zoneLow: 98.5, zoneHigh: 101.5, entryLow: 100, entryHigh: 101, zoneSource: "FVG", timeframe: "1h", confirmationTime: ready ? 5 : null }, takeProfits: [101, 102, 103, 104, 105].map((price, i) => ({ price, exitPct: [30, 25, 20, 15, 10][i], available: true })) });
  let row = mkRow(false, "WAIT_CONFIRMATION"); let memory = {};
  let step = transitionMonitor(memory, evaluateMonitor("ABCUSDT", row, 99), row, 1000); memory = step.memory;
  assert.equal(step.alert, false); assert.deepEqual(step.updates, []);
  step = transitionMonitor(memory, evaluateMonitor("ABCUSDT", row, 100.3), row, 2000); memory = step.memory;
  assert.equal(step.alert, true, "at trigger alerts once");
  step = transitionMonitor(memory, evaluateMonitor("ABCUSDT", row, 100.4), row, 3000); memory = step.memory;
  assert.equal(step.alert, false, "no repeat within 15 minutes");
  row = mkRow(true, "READY");
  step = transitionMonitor(memory, evaluateMonitor("ABCUSDT", row, 100.1), row, 4000); memory = step.memory;
  assert.ok(step.updates.includes("PLAN UPDATED") || step.updates.includes("CONFIRMED"), "candle close reported");
  assert.equal(step.alert, true, "entry range alerts");
  assert.ok(memory.armed, "armed on entry range");
  step = transitionMonitor(memory, evaluateMonitor("ABCUSDT", row, 102.5), row, 5000); memory = step.memory;
  assert.deepEqual(step.exits.map(e => e.level), [1, 2]);
  step = transitionMonitor(memory, evaluateMonitor("ABCUSDT", row, 94), row, 6000); memory = step.memory;
  assert.equal(step.exits[0].kind, "STOP"); assert.equal(memory.armed, null);
  assert.equal(step.followUp, true);
});
test("Runner rule and maximum hold produce LEAVE events; skipped plans are not armed", () => {
  const { checkExits, transitionMonitor } = mod.exports;
  const plan = { symbol: "ABCUSDT", side: "LONG", planKey: "k", entry: 100, stop: 95, targets: [101, 102, 103, 104, 105], weights: [30, 25, 20, 15, 10], hit: 0, armedAt: 0, style: "DAY" };
  let step = checkExits(plan, 102.5, 1000); assert.equal(step.next.hit, 2); assert.equal(step.next.tp2At, 1000);
  step = checkExits(step.next, 100.9, 2000); assert.equal(step.events[0].kind, "CLOSE"); assert.match(step.events[0].reason, /returned to target 1/); assert.equal(step.next, null);
  step = checkExits({ ...plan, hit: 2, tp2At: 0 }, 102.2, 121 * 60_000); assert.equal(step.events[0].kind, "CLOSE"); assert.match(step.events[0].reason, /timed out/);
  step = checkExits({ ...plan, armedAt: 0 }, 100.5, 4321 * 60_000); assert.equal(step.events[0].kind, "CLOSE"); assert.match(step.events[0].reason, /maximum hold/);
  const row = { symbol: "ABCUSDT", bias: "LONG", stop: 95, entryReady: true, style: "DAY", executionPlan: { side: "LONG", status: "READY", trigger: 100, entry: 100.2, zoneLow: 98.5, zoneHigh: 101.5, entryLow: 100, entryHigh: 101, zoneSource: "FVG", timeframe: "1h", confirmationTime: 5 }, takeProfits: [101, 102, 103, 104, 105].map((price, i) => ({ price, exitPct: [30, 25, 20, 15, 10][i], available: true })) };
  const entry = evaluateMonitor("ABCUSDT", row, 100.1);
  assert.equal(transitionMonitor({ skipped: entry.planKey }, entry, row, 1).memory.armed, undefined, "skipped plan stays unarmed");
  assert.ok(transitionMonitor({}, entry, row, 1).memory.armed, "otherwise armed");
});
